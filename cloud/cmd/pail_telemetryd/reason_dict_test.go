// P20-N1 (preview.20 evaluation): the dashboard's reason dictionary is a generated derivative of the reason
// registry, but nothing in the public Core tree compared the two — a stale reason_dict.js passed `go test`.
// This test reads the embedded dictionary and requires it to name exactly the registry's codes, values and
// planes, so a recipient who adds a reason and forgets the dictionary sees it here, not on the dashboard.
var reasonDictRow = regexp.MustCompile(`^\s*(\d+): \{ code: "([A-Z0-9_]+)", hex: "0x([0-9a-f]{2})", plane: "([A-Z]+)"`)

func TestDashboardReasonDictMatchesRegistry(t *testing.T) {
	js, err := dashboardFS.ReadFile("dashboard/reason_dict.js")
	if err != nil {
		t.Fatalf("embedded reason_dict.js: %v", err)
	}
	type row struct {
		value uint16
		plane string
	}
	got := map[string]row{}
	for _, line := range strings.Split(string(js), "\n") {
		m := reasonDictRow.FindStringSubmatch(line)
		if m == nil {
			continue
		}
		v, err := strconv.ParseUint(m[1], 10, 16)
		if err != nil {
			t.Fatalf("dictionary key %q: %v", m[1], err)
		}
		h, _ := strconv.ParseUint(m[3], 16, 16)
		if h != v {
			t.Errorf("%s: key %d and hex 0x%s disagree", m[2], v, m[3])
		}
		if _, dup := got[m[2]]; dup {
			t.Errorf("%s listed twice", m[2])
		}
		got[m[2]] = row{value: uint16(v), plane: m[4]}
	}
	want := reason.All()
	if len(got) == 0 {
		t.Fatal("no dictionary rows parsed — the generated format changed; update reasonDictRow with it")
	}
	for _, e := range want {
		g, ok := got[e.Code]
		if !ok {
			t.Errorf("registry code %s (0x%02x) is missing from dashboard/reason_dict.js — the dictionary is generated by the maintainers from the registry; open an issue or note the code in your pull request and it is regenerated before merge", e.Code, e.Value)
			continue
		}
		if g.value != e.Value {
			t.Errorf("%s: dictionary value %d, registry %d", e.Code, g.value, e.Value)
		}
		if g.plane != e.Plane.String() {
			t.Errorf("%s: dictionary plane %s, registry %s", e.Code, g.plane, e.Plane)
		}
		delete(got, e.Code)
	}
	for code, g := range got {
		t.Errorf("dictionary names %s (%d) which the registry does not have", code, g.value)
	}
	if len(want) == 0 {
		t.Fatal("empty registry")
	}
}
