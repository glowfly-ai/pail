"""spec_bundle_check.py — the license boundary between PAIL-Core and PAIL-Issuer.

The public tree is two bundles: PAIL-Core (Apache-2.0, everything outside
cloud/issuer/) and PAIL-Issuer (cloud/issuer/ plus a few declared
files). The boundary is a rule, so it needs an observation point that is not
the rule's own text. This tool measures it from the bytes.

Layouts (same routing, different inputs):
  internal  scripts/spec_bundle_check.py — the file set and each file's bundle come
            from oss/PUBLIC_TREE.tsv (INCLUDE rows, fourth column); PRIVATE rows are
            the files that must never be shipped.
  public    spec/tools/spec_bundle_check.py — the tree itself is the file set; the
            bundle is cloud/issuer/ plus the files this tool DECLARES by name
            (B_OUTSIDE_ISSUER). The declaration lives in the tree, so a bare git
            checkout measures everything; a delivery manifest, when one that
            belongs to this release is beside the tree, is only cross-checked.

Observation points:
  B1  direction — no Go file outside the issuer directory imports the issuer module
      path, except a _test.go that imports only issuer/testissuer and carries the
      issuer-bundle SPDX header (the declared seam); issuer files may import anything.
  B2  headers — source files under the issuer bundle carry the issuer-bundle SPDX
      identifier (SPDX_B below), all other public
      source files say Apache-2.0; protoc output is exempt by its own marker.
  B3  issuer license — cloud/issuer/LICENSE, when that bundle is in the tree, is the
      licence text the bundle declares (SPDX_B) with the four
      parameters filled: Change Date is a real date inside [release date,
      release date + 4 years], Change License is Apache License, Version 2.0,
      Additional Use Grant is not empty.
  B4  private set — the replication extension (issuer/internal/ha, proto/hav1,
      ha_replication.proto, ha_sync.go, proto_golden_ha_test.go) is PRIVATE in the
      internal manifest and absent from a public tree.
  B5  seam — cmd/pail_cloud/ha_seam.go declares haRequestedWithoutExtension and
      main.go calls it before binding a port; the refusal is not just a comment.
  B6  bundle B carries its own NOTICE and README; the root LICENSE is Apache-2.0.
  B7  declared outside files — every path in B_OUTSIDE_ISSUER is present when
      cloud/issuer/ is (absent when it is not) and states SPDX_B in its prologue;
      in the internal layout the declaration equals the PUBLIC_TREE bundle-B rows
      outside the issuer directory; a delivery manifest of this release, if found,
      labels exactly these paths (and cloud/issuer/) as issuer.
  B8  reverse direction — a file outside cloud/issuer/ whose prologue states
      SPDX_B must be in B_OUTSIDE_ISSUER. The header may not claim a bundle the
      declaration does not know.

Exit: 0 pass · 1 finding · 2 cannot check (missing input, unknown layout).
"""
import datetime
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))

ISSUER_MOD = "github.com/glowfly/pail/services/issuer/"
SEAM_IMPORT = "github.com/glowfly/pail/services/issuer/testissuer"
SPDX_A = "SPDX-License-Identifier: Apache-2.0"
# The identifier the issuer bundle's source files carry in the tree where that bundle exists. A PAIL-Core
# delivery contains none of those files and grants no such licence: the Issuer it ships is an evaluation
# executable under EVALUATION-LICENSE.txt (see ISSUER_EVALUATION.md). B1-B8 measure the boundary, not terms.
SPDX_B = "SPDX-License-Identifier: BUSL-1.1"
SPDX_ANY = "SPDX-License-Identifier:"
SRC_EXT = (".go", ".cpp", ".hpp", ".proto", ".py", ".sh")
GENERATED = ("Code generated by", "DO NOT EDIT")
PROLOGUE = 8
# Public paths. The internal manifest maps them to internal paths.
ISSUER_DIR = "cloud/issuer/"
# The declaration of bundle-B files that live OUTSIDE cloud/issuer/. In a public tree this
# is the authority. Three external reviews on 2026-09-18 put it here:
#   · path inference cannot, in principle, see a bundle-B file outside the directory;
#   · an authority kept outside the tree (the delivery manifest) creates two new cases —
#     an environment that does not have that file (the public CI works from a bare
#     checkout) and a file that is wrong (another release's manifest, or a table that is
#     internally consistent and still false).
# So the authority lives in the tree, by name. The internal layout compares it with
# PUBLIC_TREE so the two cannot drift, and a delivery manifest is only cross-checked.
# The block between the two markers is GENERATED by the maintainer's tree generator from its
# own list of bundle-B files and compared byte for byte in CI. Do not edit it by hand: a new
# bundle-B file outside the directory is added in one place and appears here by generation.
# bundle-declaration:start
B_OUTSIDE_ISSUER = (
    "cloud/cmd/pail_robot_agent/dn4_proxy_test.go",
    "cloud/cmd/pail_robot_agent/hwa1_wire_test.go",
    "examples/perf/WORKLOADS.yaml",
)
# bundle-declaration:end
# Only an SPDX line in the prologue counts as a header, and it has to start with a comment
# leader. A string literal in a file's body (SPDX_B in this file, the positive controls in
# the CI workflow) must not be read as that file's license header.
RE_SPDX_BUSL_LINE = re.compile(r"^\s*(?:#|//|/\*|\*|<!--|;|--)\s*SPDX-License-Identifier:\s*BUSL-1\.1\b")
MANIFEST_NOTES = []  # delivery manifests used or ignored for the cross-check, with the reason (printed)
PRIVATE_PUBLIC = (
    "cloud/issuer/internal/ha/",
    "cloud/proto/hav1/",
    "sdk/proto/ha_replication.proto",
    "cloud/issuer/cmd/pail_cloud/ha_sync.go",
    "cloud/internal/contract/proto_golden_ha_test.go",
)
GO_IMPORT = re.compile(r'^\s*(?:[\w.]+\s+)?"([^"]+)"\s*$', re.M)

LAYOUTS = (
    ("internal", ("scripts",), "oss/PUBLIC_TREE.tsv", "oss/release.json"),
    ("public", ("spec", "tools"), None, "release.json"),
)


def die(msg):
    print("spec_bundle_check: CANNOT_CHECK: %s" % msg)
    sys.exit(2)


def read(path):
    try:
        with open(path, "r", encoding="utf-8", errors="replace") as fh:
            return fh.read()
    except OSError as exc:
        die("cannot read %s (%s)" % (path, exc))


def locate():
    parts = HERE.replace(os.sep, "/").split("/")
    hits = []
    for name, tail, tree, release in LAYOUTS:
        if len(parts) > len(tail) and tuple(parts[-len(tail):]) == tail:
            root = os.path.abspath(os.path.join(HERE, *([".."] * len(tail))))
            hits.append((name, root, tree and os.path.join(root, *tree.split("/")),
                         os.path.join(root, *release.split("/"))))
    if len(hits) != 1:
        die("cannot determine layout (%d matches) from %s" % (len(hits), HERE))
    return hits[0]


def delivery_manifest_table(root, release_id, tree_files):
    """Return the bundle table of a delivery manifest that belongs to this release, or None.

    The manifest is a cross-check target, not the authority, so adoption is strict: its
    release_id must equal this tree's VERSION and its file set must equal this tree's.
    A candidate that fails is dropped, and the summary line says which one and why — it is
    neither adopted silently nor discarded silently.
      · A manifest NAMED through PAIL_RELEASE_MANIFEST that fails those conditions is
        exit 2: the cross-check that was asked for cannot be performed.
      · A foreign manifest met by discovery is just a file lying next to the tree — it is
        recorded and skipped.
    """
    explicit = os.environ.get("PAIL_RELEASE_MANIFEST")
    candidates = []
    if explicit:
        candidates.append((explicit, True))
    else:
        for d in (os.path.dirname(os.path.abspath(root)), os.path.abspath(root)):
            try:
                names = sorted(n for n in os.listdir(d) if n.endswith(".manifest.json"))
            except OSError:
                continue
            candidates += [(os.path.join(d, n), False) for n in names]
    for path, is_explicit in candidates:
        base = os.path.basename(path)
        reason = None
        try:
            data = json.loads(read(path))
        except (ValueError, OSError, SystemExit):
            data, reason = None, "unreadable"
        if data is not None:
            table = data.get("source_files_bundle")
            if not isinstance(table, dict):
                reason = "no source_files_bundle"
            elif data.get("release_id") != release_id:
                reason = "release_id %r != tree %r" % (data.get("release_id"), release_id)
            elif set(table) != set(tree_files):
                reason = "different file set (manifest %d, tree %d)" % (len(table), len(tree_files))
        if reason is None:
            MANIFEST_NOTES.append("used:" + base)
            return table
        if is_explicit:
            die("PAIL_RELEASE_MANIFEST=%s cannot be cross-checked against this tree: %s"
                % (path, reason))
        MANIFEST_NOTES.append("ignored:%s(%s)" % (base, reason))
    return None


def shipped(layout, root, tree):
    """{public path: (real path, bundle)} plus the set of PRIVATE public paths."""
    files, private = {}, set()
    if layout == "public":
        for dirpath, dirnames, filenames in os.walk(root):
            dirnames[:] = [d for d in dirnames if d != ".git"]
            for fn in filenames:
                p = os.path.join(dirpath, fn)
                rel = os.path.relpath(p, root).replace(os.sep, "/")
                # Authority: the directory rule plus the files declared by name — neither path
                # inference nor a manifest.
                member = "B" if (rel.startswith(ISSUER_DIR) or rel in B_OUTSIDE_ISSUER) else "A"
                files[rel] = (p, member)
        if not files:
            die("public tree is empty")
        return files, private
    split_delivery = json.loads(read(os.path.join(root, 'oss/release.json'))).get('schema_version') == 3
    for ln in read(tree).splitlines():
        if ln.startswith("#") or not ln.strip():
            continue
        cells = ln.split("\t")
        if len(cells) != 5:
            die("manifest row is not five columns: %s" % ln[:80])
        st, src, pub, bundle = cells[0], cells[1], cells[2], cells[3]
        if st == "PRIVATE":
            private.add(pub)
        elif st == "INCLUDE":
            if bundle not in ("A", "B"):
                die("INCLUDE row with bundle %r: %s" % (bundle, pub))
            if split_delivery and bundle == "B":
                private.add(pub)  # internal build inventory, never a source deliverable
                continue
            files[pub] = (os.path.join(root, *src.split("/")), bundle)
    if not files:
        die("no INCLUDE rows in %s" % tree)
    return files, private


def go_imports(text):
    out = []
    for block in re.findall(r"^import\s*\((.*?)^\)", text, flags=re.M | re.S):
        out += GO_IMPORT.findall(block)
    out += re.findall(r'^import\s+(?:[\w.]+\s+)?"([^"]+)"', text, flags=re.M)
    return out


def parse_params(text):
    """The licence-parameters block of the issuer bundle's LICENSE (Key: value; values may continue on indented lines)."""
    m = re.search(r"^Parameters\s*$(.*?)^Notice\s*$", text, flags=re.M | re.S)
    if not m:
        return None
    params, key = {}, None
    for ln in m.group(1).splitlines():
        km = re.match(r"^([A-Z][A-Za-z ]+):\s*(.*)$", ln)
        if km and km.group(1) in ("Licensor", "Licensed Work", "Additional Use Grant", "Change Date", "Change License"):
            key = km.group(1)
            params[key] = km.group(2).strip()
        elif key and ln.strip():
            params[key] += " " + ln.strip()
    return params


def main():
    layout, root, tree, release_path = locate()
    files, private = shipped(layout, root, tree)
    fails = []
    n_dir, n_hdr_a, n_hdr_b, n_seam = 0, 0, 0, 0

    # B1 direction + B2 headers (one pass over the source files).
    for pub in sorted(files):
        real, bundle = files[pub]
        if not pub.endswith(SRC_EXT):
            continue
        text = read(real)
        if all(mark in text[:400] for mark in GENERATED):
            continue
        prologue = text.splitlines()[:PROLOGUE]
        want = SPDX_B if bundle == "B" else SPDX_A
        if not any(want in ln for ln in prologue):
            fails.append("B2: %s (bundle %s) does not carry '%s' in its first %d lines"
                         % (pub, bundle, want, PROLOGUE))
        else:
            if bundle == "B":
                n_hdr_b += 1
            else:
                n_hdr_a += 1
        if pub.endswith(".go") and not pub.startswith(ISSUER_DIR):
            n_dir += 1
            issuer_imports = [i for i in go_imports(text) if i.startswith(ISSUER_MOD)]
            if not issuer_imports:
                continue
            if not pub.endswith("_test.go"):
                fails.append("B1: %s (PAIL-Core, non-test) imports the issuer: %s"
                             % (pub, ", ".join(issuer_imports)))
                continue
            if set(issuer_imports) != {SEAM_IMPORT}:
                fails.append("B1: %s imports issuer packages other than the declared seam: %s"
                             % (pub, ", ".join(sorted(set(issuer_imports) - {SEAM_IMPORT}))))
                continue
            if bundle != "B" or not any(SPDX_B in ln for ln in prologue):
                fails.append("B1: %s uses the declared seam but is not bundle B with the issuer-bundle SPDX header" % pub)
                continue
            n_seam += 1
    if n_dir == 0:
        die("no PAIL-Core Go files found — the direction check measured nothing")
    # A PAIL-Core-only tree legitimately has no issuer directory. That is a fact to
    # print, not a pass to assume: B3/B5/B6 are then not applicable and say so. The
    # internal manifest always carries bundle B.
    has_issuer = any(k.startswith(ISSUER_DIR) for k in files)
    split_delivery = json.loads(read(release_path)).get("schema_version") == 3
    if split_delivery and has_issuer:
        fails.append("B2: private Issuer source leaked into the new Core distribution")
    if layout == "internal" and not has_issuer and not split_delivery:
        fails.append("B2: the manifest carries no cloud/issuer/ rows — bundle B is missing from the release")
    if has_issuer and n_hdr_b == 0:
        fails.append("B2: no bundle-B source file was measured — the issuer bundle is empty or unlabeled")
    if not has_issuer:
        print("spec_bundle_check: bundle B (cloud/issuer/) is absent from this tree — PAIL-Core only; "
              "B3/B5/B6 not applicable, B1/B2/B4 measured")

    # B3 issuer license parameters.
    lic = files.get(ISSUER_DIR + "LICENSE") if has_issuer else None
    rel_date = None
    try:
        rid = json.loads(read(release_path))["release_id"]
        m = re.search(r"-rc\.(\d{4})(\d{2})(\d{2})\.", rid)
        if m:
            rel_date = datetime.date(int(m.group(1)), int(m.group(2)), int(m.group(3)))
    except (OSError, ValueError, KeyError):
        rel_date = None
    if lic is None:
        if has_issuer:
            fails.append("B3: %sLICENSE is not shipped" % ISSUER_DIR)
    else:
        text = read(lic[0])
        if "Business Source License 1.1" not in text or "Covenants of Licensor" not in text:
            fails.append("B3: issuer LICENSE is not the Business Source License 1.1 text")
        params = parse_params(text) or {}
        for key in ("Licensor", "Licensed Work", "Additional Use Grant", "Change Date", "Change License"):
            if not params.get(key):
                fails.append("B3: issuer LICENSE parameter '%s' is missing or empty" % key)
        if params.get("Change License") and "Apache License, Version 2.0" not in params["Change License"]:
            fails.append("B3: Change License is not the Apache License, Version 2.0: %r" % params["Change License"])
        cd = params.get("Change Date", "")
        dm = re.fullmatch(r"(\d{4})-(\d{2})-(\d{2})", cd)
        if not dm:
            fails.append("B3: Change Date must be a YYYY-MM-DD date, not %r (BUSL covenant 3)" % cd)
        elif rel_date is None:
            fails.append("B3: cannot read the release date from %s to bound the Change Date" % release_path)
        else:
            change = datetime.date(int(dm.group(1)), int(dm.group(2)), int(dm.group(3)))
            cap = datetime.date(rel_date.year + 4, rel_date.month, rel_date.day)
            if not (rel_date <= change <= cap):
                fails.append("B3: Change Date %s is outside [%s, %s] (release date, +4 years)" % (change, rel_date, cap))
        if "None" == params.get("Additional Use Grant", "").strip():
            fails.append("B3: Additional Use Grant is 'None' — the policy opens non-commercial production use")

    # B4 private set.
    for p in PRIVATE_PUBLIC:
        present = [k for k in files if k == p or (p.endswith("/") and k.startswith(p))]
        if present:
            fails.append("B4: private path shipped: %s (%d files)" % (p, len(present)))
        if layout == "internal":
            listed = [k for k in private if k == p or (p.endswith("/") and k.startswith(p))]
            if not listed:
                fails.append("B4: %s is not a PRIVATE row in the manifest — if it left the tree, delete it here too" % p)

    # B5 seam vocabulary.
    seam = files.get(ISSUER_DIR + "cmd/pail_cloud/ha_seam.go")
    mainf = files.get(ISSUER_DIR + "cmd/pail_cloud/main.go")
    if seam is None or mainf is None:
        if has_issuer:
            fails.append("B5: %scmd/pail_cloud/{ha_seam.go,main.go} not shipped" % ISSUER_DIR)
    else:
        if "func haRequestedWithoutExtension(" not in read(seam[0]):
            fails.append("B5: ha_seam.go does not define haRequestedWithoutExtension")
        mt = read(mainf[0])
        if "haRequestedWithoutExtension(haExt, os.Environ())" not in mt:
            fails.append("B5: main.go does not call haRequestedWithoutExtension(haExt, os.Environ())")
        elif mt.index("haRequestedWithoutExtension(") > mt.index("net.Listen("):
            fails.append("B5: main.go binds the port before refusing a replication configuration")

    # B6 bundle documents.
    for p in ("NOTICE", "README.md"):
        if has_issuer and ISSUER_DIR + p not in files:
            fails.append("B6: %s%s is not shipped" % (ISSUER_DIR, p))
    rootlic = files.get("LICENSE")
    if rootlic is None or "Apache License" not in read(rootlic[0])[:400]:
        fails.append("B6: root LICENSE is missing or is not the Apache License")

    def states_busl(real):
        """Does a COMMENT line in the prologue (the first PROLOGUE lines) state the issuer-bundle SPDX identifier (SPDX_B)?"""
        return any(RE_SPDX_BUSL_LINE.match(ln) for ln in read(real).splitlines()[:PROLOGUE])

    # B7: the declared outside files — present when they have to be, and stating SPDX_B in
    #     their own header. Inside cloud/issuer/ that directory's LICENSE covers a file;
    #     outside it, the header is the only place that can say so.
    declared = set(B_OUTSIDE_ISSUER)
    n_outside = 0
    for pub in sorted(declared):
        if pub.startswith(ISSUER_DIR):
            die("B_OUTSIDE_ISSUER lists a path inside %s: %s" % (ISSUER_DIR, pub))
        entry = files.get(pub)
        if has_issuer and entry is None:
            # The count may not shrink silently (an earlier candidate counted 3 files as 2).
            fails.append("B7: declared bundle-B file %s is missing from a tree that carries %s"
                         % (pub, ISSUER_DIR))
            continue
        if not has_issuer:
            if entry is not None:
                fails.append("B7: %s is a PAIL-Issuer file but this tree has no %s — "
                             "a bundle-B file leaked into PAIL-Core" % (pub, ISSUER_DIR))
            continue
        n_outside += 1
        if entry[1] != "B":
            fails.append("B7: %s is declared bundle B but the internal manifest says %s"
                         % (pub, entry[1]))
        if not states_busl(entry[0]):
            fails.append("B7: %s is bundle B outside %s but does not state %s — "
                         "neither the directory rule nor an SPDX header can classify it"
                         % (pub, ISSUER_DIR, SPDX_B))
    if layout != "public":
        # The declaration and the internal authority (the bundle column of PUBLIC_TREE) must be
        # the same set. Editing only one of them is a finding.
        rows_b_outside = set(k for k, (_, bd) in files.items()
                             if bd == "B" and not k.startswith(ISSUER_DIR))
        if split_delivery:
            # B remains an internal binary-build inventory; validate its declaration without exporting it.
            rows_b_outside = {c[2] for line in read(tree).splitlines()
                              if line.startswith('INCLUDE\t')
                              for c in [line.split('\t')]
                              if c[3] == 'B' and not c[2].startswith(ISSUER_DIR)}
        for pub in sorted(rows_b_outside - declared):
            fails.append("B7: PUBLIC_TREE ships %s as bundle B outside %s but B_OUTSIDE_ISSUER "
                         "does not declare it — a public tree could not classify it"
                         % (pub, ISSUER_DIR))
        for pub in sorted(declared - rows_b_outside):
            if pub in files:  # already reported above as "not bundle B"; do not report it twice
                continue
            fails.append("B7: B_OUTSIDE_ISSUER declares %s but PUBLIC_TREE has no such INCLUDE row"
                         % pub)

    # B8: the reverse direction — a header outside the directory that states SPDX_B has to be
    #     declared. (A table that was consistently wrong used to pass although the file's own
    #     first line contradicted it; nothing looked in that direction.)
    n_reverse = 0
    for pub in sorted(files):
        if pub.startswith(ISSUER_DIR):
            continue
        n_reverse += 1
        if pub not in declared and states_busl(files[pub][0]):
            fails.append("B8: %s states %s in its prologue but is not declared in "
                         "B_OUTSIDE_ISSUER — the header claims a bundle the declaration "
                         "does not know" % (pub, SPDX_B))
    if n_reverse == 0:
        die("no file outside %s — B8 measured nothing" % ISSUER_DIR)

    # Delivery manifest: cross-checked when present. Its issuer set must be exactly
    # cloud/issuer/ plus the declaration.
    manifest_basis = "n/a(internal)"
    if layout == "public":
        release_id = read(os.path.join(root, "VERSION")).strip()
        table = delivery_manifest_table(root, release_id, files)
        if table is not None:
            for pub in sorted(files):
                want = "issuer" if files[pub][1] == "B" else "core"
                if table.get(pub) != want:
                    fails.append("B7: delivery manifest labels %s as %r but this tree's "
                                 "declaration says %r" % (pub, table.get(pub), want))
        manifest_basis = ";".join(MANIFEST_NOTES) if MANIFEST_NOTES else "absent"

    print("spec_bundle_check: layout=%s core_go=%d headers(A=%d,B=%d) seam_tests=%d "
          "b_outside_issuer=%d/%d b7_basis=in-tree reverse_checked=%d manifest=%s private_rows=%d"
          % (layout, n_dir, n_hdr_a, n_hdr_b, n_seam, n_outside,
             len(declared) if has_issuer else 0, n_reverse, manifest_basis, len(private)))
    for f in fails:
        print("FAIL " + f)
    print("BUNDLE-BOUNDARY: %s (%d findings)" % ("FAIL" if fails else "PASS", len(fails)))
    return 1 if fails else 0

if __name__ == "__main__":
    sys.exit(main())
