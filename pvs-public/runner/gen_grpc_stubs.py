"""Generate the PVS live runner's Python gRPC stubs from proto/*.proto with the pinned toolchain.

The six generated modules are bundled in the public tree (preview.38, owner decision 2026-10-26). This script is the
one way to produce them: it runs grpc_tools.protoc and prepends the license header every public file carries, so a
fresh run into a temporary directory must be byte-identical to the bundled files (tests/contract/test_pvs_stubs_match_proto.py).

    python3 pvs/runner/gen_grpc_stubs.py            # regenerate in place (pvs/runner/live)
    python3 pvs/runner/gen_grpc_stubs.py --out DIR  # generate elsewhere (the gate's fresh copy)
"""
import argparse,subprocess,sys
from importlib.metadata import version
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
PROTOS=['pail.proto','token_service.proto','operator_service.proto']
PINNED={'grpcio':'1.83.0','grpcio-tools':'1.83.0','protobuf':'7.35.1'}
HEADER=('# SPDX-License-Identifier: Apache-2.0\n'
        '# Copyright 2026 Glowfly Identity Systems Co.,Ltd\n'
        '# Generated by pvs/runner/gen_grpc_stubs.py (grpcio-tools %s, protobuf %s) from proto/%s. DO NOT EDIT.\n')

def main():
    ap=argparse.ArgumentParser();ap.add_argument('--out',type=Path,default=ROOT/'pvs/runner/live');ap.add_argument('--no-version-check',action='store_true')
    a=ap.parse_args()
    got={k:version(k) for k in PINNED}
    if got!=PINNED and not a.no_version_check:
        sys.exit('toolchain is not the pinned one: %s (pinned %s); see pvs/runner/gen_grpc_stubs.md'%(got,PINNED))
    a.out.mkdir(parents=True,exist_ok=True)
    subprocess.run([sys.executable,'-m','grpc_tools.protoc','-I',str(ROOT/'proto'),'--python_out',str(a.out),'--grpc_python_out',str(a.out)]
                   +[str(ROOT/'proto'/p) for p in PROTOS],check=True)
    for p in PROTOS:
        stem=p[:-6]
        for name in (stem+'_pb2.py',stem+'_pb2_grpc.py'):
            f=a.out/name;body=f.read_text(encoding='utf-8')
            f.write_text(HEADER%(got['grpcio-tools'],got['protobuf'],p)+body,encoding='utf-8')
    print('generated',', '.join(sorted(x.name for x in a.out.glob('*_pb2*.py'))),'in',a.out)

if __name__=='__main__':
    main()
